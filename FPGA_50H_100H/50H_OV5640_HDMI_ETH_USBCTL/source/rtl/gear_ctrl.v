`timescale 1ns / 1ps
//////////////////////////////////////////////////////////////////////////////////
// gear_ctrl — 亮度自适应档位决策（模块 A 的判定级）
// 261028e 重新标定 / 261031 配合 frame_stat 的四分之一帧窗口
//
// 语义：一个开关 l_en 管两个方向。开 = 按统计自动选档，关 = 直通。
//
//   bank 0 : identity          直通（目标区）
//   bank 1 : G0  u^0.85        轻微提亮  (mean_v 88~107)
//   bank 2 : G1  u^0.68        中提亮    (66~87)
//   bank 3 : G2  u^0.52        强提亮    (40~65)
//   bank 4 : G3  u^0.40        极暗提亮  (<40)
//   bank 5 : D1  0.625*u^0.95  轻微压暗  (dark_score 120~149)
//   bank 6 : D2  0.43*u^0.90   中压暗    (150~179)
//   bank 7 : D3  0.19*u^0.80   强压暗    (>=180)
//   （261031e：三档强度 (1-g) 统一提到上一版的 150%，同时把三条门限各降 20。
//     261031d 那次是 g 同比降 12%（0.85/0.70/0.52 -> 0.75/0.62/0.46），
//     现场反馈"压暗看不出来"，故本次直接 1.5 倍并放宽触发。
//     曲线表在 tone_lut.v，此处只列名义参数，改表必须两边一起改。）
//
// ---- 261028e 改了三处（都是"效果不明显"的直接原因）--------------------------
// ① 判据分两个方向用两个量
//    提亮看 mean_v（剔除顶满像素的均值）—— 夜里一盏车灯不该把整帧判成白天。
//    压暗看 dark_score = mean_v + (255-mean_v)*高亮占比 —— 过曝画面里被剔掉的
//    正是我们想压的那部分，只看 mean_v 会漏判。
// ② 删掉"cnt_sat > 5% 就冻结档位"
//    这个条件恰恰在过曝画面成立 → 越该压暗越冻结在 bank 0，等于压暗永远不生效。
//    现在只在"有效像素 < 5%"（整窗过曝、统计失效）时强制走 D3。
// ③ 删掉"cnt_hi > 8% 时提亮最高只到 G1"
//    幂律 u^p 的两端固定在 0 和 N，提亮本身不会把高光顶飞，这条限制只剩副作用。
//
// ---- 261031：判决节拍跟着统计窗口走 -----------------------------------------
//   frame_stat 现在一帧滚出 4 个 mean_v（推进单元 = 180 行），本模块只在
//   frame_vld（帧内第 4 个窗口）上判决 —— 即"每帧判一次"，且判决点正好落在
//   垂直消隐前的帧边界，换档不会切出上下半帧不同曲线。
//   目标连续两次一致才允许动：2 帧 ≈ 33 ms（旧版是 mean_vld 每帧一次、每 4 次
//   才判一次，要 8 帧 ≈ 133 ms），时延缩到 1/4。
//   阈值仍是按"整帧均值"标定的 —— frame_stat 送来的 mean_v 是最近 4 个窗口的
//   滚动和（整帧覆盖），所以七段门限一个都不用重标定。
//
// 换档规则：
//   · 每次判决：目标连续两次一致才允许动
//   · 同一支内（1..4 或 5..7）单次只走 ±1 档
//   · 跨支（直通 ↔ 提亮 ↔ 压暗）一步到位 —— 反向渐变要先经过"更亮/更暗"的
//     错误中间态，这正是旧版按下增暗反而先变亮的原因
//////////////////////////////////////////////////////////////////////////////////
module gear_ctrl (
    input               clk,
    input               rst_n,
    input               mean_vld,       // 每个统计窗口末 1 拍（每帧 4 次）
    input               frame_vld,      // 与 mean_vld 同拍，标记帧内最后一个窗口
    input       [7:0]   mean_v,
    input       [19:0]  cnt_v,          // 最近 4 窗口的非顶满样本数（统计有效性）
    input       [19:0]  cnt_hi,         // 最近 4 窗口 Y>=240 的样本数（压暗侧加权）
    input               l_en,           // 亮度自适应开关（帧边界锁存）

    output      [2:0]   bank,           // tone_lut 库号
    output      [1:0]   gear            // 调试用：支内序号 0..3
);

    //------------------------------------------------------------------
    // 七段阈值（曲线形状见 tone_lut.v 头）
    //------------------------------------------------------------------
    localparam [7:0] T_G3 = 8'd40;    // 低于此 -> G3（极暗）
    localparam [7:0] T_G2 = 8'd66;
    localparam [7:0] T_G1 = 8'd88;
    localparam [7:0] T_G0 = 8'd108;
    localparam [8:0] T_D1 = 9'd120;   // 高于此 -> 开始压暗（261031e: 140 -> 120）
    localparam [8:0] T_D2 = 9'd150;   // 261031e: 170 -> 150
    localparam [8:0] T_D3 = 9'd180;   // 261031e: 200 -> 180

    // 261031：统计窗口 = 1/4 帧（180 行）x 4x4 抽取 = 14400 样本；
    //   frame_stat 送来的 mean_v/cnt_v/cnt_hi 是**最近 4 个窗口的滚动和**
    //   （= 整帧覆盖，57,600 样本），所以下面的门限按 57600 算：
    //   5% x 57600 = 2880。
    //   旧值 46080 是"整帧 921600 的 5%"，放到 57600 的新规模里等于 80% ——
    //   会把"整窗过曝"的保护彻底废掉，所以必须跟着改。
    localparam [19:0] CNT_V_MIN = 20'd2880;    // 5% x 57600

    //------------------------------------------------------------------
    // dark_score = mean_v + (255-mean_v) * cnt_hi / N_WIN
    //   等价于"把顶满像素也算进均值"，但不用第二个除法器：
    //   (255-mean_v)*cnt_hi >> 16 ≈ (255-mean_v) x 比例（65536/57600 = 1.138,
    //   即系数 0.879，与旧版 >>20 / 921600 的保守量完全一致）
    //------------------------------------------------------------------
    wire [7:0]  dv_inv  = 8'd255 - mean_v;
    wire [23:0] dprod   = dv_inv * cnt_hi[15:0];
    wire [7:0]  dbump   = dprod[23:16];
    wire [8:0]  dark_sc = {1'b0, mean_v} + {1'b0, dbump};

    //------------------------------------------------------------------
    // 状态寄存器
    //------------------------------------------------------------------
    reg  [2:0] bank_d;
    reg        tgt_prev_en;
    reg  [2:0] tgt_prev;

    //------------------------------------------------------------------
    // 目标档
    //------------------------------------------------------------------
    reg [2:0] t_dec;
    always @(*) begin
        if      (mean_v  < T_G3) t_dec = 3'd4;   // G3
        else if (mean_v  < T_G2) t_dec = 3'd3;   // G2
        else if (mean_v  < T_G1) t_dec = 3'd2;   // G1
        else if (mean_v  < T_G0) t_dec = 3'd1;   // G0
        else if (dark_sc < T_D1) t_dec = 3'd0;   // 直通（目标区 108~119）
        else if (dark_sc < T_D2) t_dec = 3'd5;   // D1
        else if (dark_sc < T_D3) t_dec = 3'd6;   // D2
        else                     t_dec = 3'd7;   // D3
    end

    // 支号：0 = 直通, 1 = 提亮(bank1..4), 2 = 压暗(bank5..7)
    function [1:0] br_of;
        input [2:0] b;
        begin
            br_of = (b == 3'd0) ? 2'd0 : (b <= 3'd4) ? 2'd1 : 2'd2;
        end
    endfunction

    wire [1:0] t_br = br_of(t_dec);
    wire [1:0] c_br = br_of(bank_d);

    // 统计几乎失效（顶满样本 > 95%）：此时 mean_v 只在剩下不到 5% 的样本上
    //   算出来，可能接近 0 → 会被误判成"极暗"而全力提亮，正好搞反。
    //   这种画面只有一个正确动作：全力压暗（D3）。
    wire all_blown   = (cnt_v < CNT_V_MIN);
    wire [2:0] t_use = all_blown ? 3'd7 : t_dec;

    //------------------------------------------------------------------
    // 换档（只在 frame_vld = 帧内最后一个窗口的 mean_vld 上判决）
    //------------------------------------------------------------------
    wire decide = mean_vld & frame_vld;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            bank_d      <= 3'd0;
            tgt_prev    <= 3'd0;
            tgt_prev_en <= 1'b0;
        end else if (mean_vld) begin
            if (!l_en) begin
                // 开关关：立刻回直通，并清一致性记录（重开时重新攒）
                bank_d      <= 3'd0;
                tgt_prev    <= 3'd0;
                tgt_prev_en <= 1'b0;
            end else if (decide) begin
                if (tgt_prev_en && (t_use == tgt_prev)) begin
                    if (t_br != c_br) begin
                        // 跨支（含进出直通）：一步到位
                        bank_d      <= t_use;
                        tgt_prev    <= t_use;
                        tgt_prev_en <= 1'b0;
                    end else begin
                        // 同支：单次 ±1 档
                        if (t_use > bank_d)      bank_d <= bank_d + 3'd1;
                        else if (t_use < bank_d) bank_d <= bank_d - 3'd1;
                        tgt_prev    <= t_use;
                        tgt_prev_en <= 1'b1;
                    end
                end else begin
                    tgt_prev    <= t_use;
                    tgt_prev_en <= 1'b1;
                end
            end
        end
    end

    //------------------------------------------------------------------
    // 输出
    //------------------------------------------------------------------
    assign bank = l_en ? bank_d : 3'd0;

    // 支内序号：1..4 -> 0..3，5..7 -> 0..2
    assign gear = (bank == 3'd0) ? 2'd0 :
                  (bank <= 3'd4) ? (bank - 3'd1) :
                                   (bank - 3'd5);

endmodule
