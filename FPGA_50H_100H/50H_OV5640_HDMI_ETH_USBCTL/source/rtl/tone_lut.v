// ---- 261031e：三档压暗再提 150% + 门限各降 20 --------------------------------
//   强度按 (1-g) 线性放大 1.5 倍：0.75/0.62/0.46 -> 0.625/0.43/0.19，p 照旧不动。
//   白点（8 bit 等价）：D1 189->156，D2 156->107，D3 115->49。
//   门限 140/170/200 -> 120/150/180（见 gear_ctrl.v 的 T_D1/T_D2/T_D3）。
//
//   ⚠ D3 只剩 7 个灰阶（R/B）：31 个输入码映射到 0..6，强压暗下会出现明显色带。
//     这是 5 bit 码宽的硬限制，不是算法问题。要保住层次就把 bank7 的 g 抬回 0.28
//     （白点 72、13 个灰阶，强度 130%）。D1/D2 分别是 20 / 14 个灰阶，尚可。
//
// ---- 为什么用幂律而不是线性增益 ------------------------------------------------
//   旧版是 i*g（g=1.15/1.35/1.60 与 0.88/0.78/0.68），作用在 5 bit 码上：
//   极限暗光下输入码 4 只能变成 6 —— 两个码，肉眼几乎看不出。
//   线性增益的绝对增量与码值成正比，所以它天然救不了暗部。
//   幂律 u^p (p<1) 在暗部的相对提升是压倒性的：
//     G3: 1->8, 2->10, 4->14, 8->18, 16->24, 31->31  （5 bit）
//   而且 u^p 的两端固定在 0 和 N —— 黑位不浮、高光不丢，不需要再加肩部压缩。
//   压暗侧用 g*u^p (g<1, p<1)：既把白点压下来（1.0->0.46），
//   又不把暗部压死（0.2 -> 0.13 而不是 0.09）。
//
//   表由脚本生成，不要手改。
